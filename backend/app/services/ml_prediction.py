import joblib
import pandas as pd
import numpy as np
import json
import os

# ─── Load Models & Feature Importances ────────────────────────────────────────
BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
clf_path = os.path.join(BASE_DIR, 'ml_models', 'shortage_classifier.pkl')
reg_path = os.path.join(BASE_DIR, 'ml_models', 'units_regressor.pkl')
imp_path = os.path.join(BASE_DIR, 'ml_models', 'feature_importances.json')

FEATURE_NAMES = ['Recency_Months', 'Frequency_Times', 'Monetary_cc', 'Time_Months', 
                 'Accident_Risk', 'Weather_Severity', 'Is_Weekend']

try:
    classifier = joblib.load(clf_path)
    regressor = joblib.load(reg_path)
    MODELS_LOADED = True
    # Load pre-computed feature importances from JSON (generated by train_models.py)
    if os.path.exists(imp_path):
        with open(imp_path) as f:
            FEATURE_IMPORTANCES = json.load(f)
    else:
        # Derive inline if JSON doesn't exist yet
        raw = classifier.feature_importances_
        FEATURE_LABELS = ['Recency', 'Donation Frequency', 'Blood Volume (cc)', 'Donor Tenure',
                          'Accident Zone Risk', 'Weather Severity', 'Weekend Demand']
        total = sum(raw)
        FEATURE_IMPORTANCES = {
            FEATURE_LABELS[i]: round(float(raw[i] / total) * 100, 1)
            for i in range(len(FEATURE_LABELS))
        }
except Exception as e:
    print(f"Warning: Could not load ML models. Ensure train_models.py has been run. {e}")
    MODELS_LOADED = False
    # Realistic fallback importances for demo purposes
    FEATURE_IMPORTANCES = {
        "Accident Zone Risk": 38.5,
        "Weather Severity": 24.2,
        "Weekend Demand": 15.7,
        "Donation Frequency": 10.3,
        "Recency": 6.8,
        "Donor Tenure": 3.1,
        "Blood Volume (cc)": 1.4
    }


def get_shortage_forecasts():
    """
    Runs live inference using the trained XGBoost (regression) and 
    RandomForest (classification) models trained on UCI Blood Transfusion data.
    Returns predictions enriched with Explainable AI feature scores for the frontend.
    """
    
    regions = [
        {
            "id": "JPR-N1",
            "name": "Jhotwara Industrial Area",
            "lat": 26.9388,
            "lng": 75.7483,
            "bloodType": "O-",
            "features": [12, 5, 1200, 24, 9, 3, 1]  # High accident risk (9)
        },
        {
            "id": "JPR-S2",
            "name": "Malviya Nagar Highway",
            "lat": 26.8530,
            "lng": 75.8174,
            "bloodType": "A+",
            "features": [6, 12, 3500, 48, 4, 6, 0]  # Severe weather (6)
        },
        {
            "id": "JPR-W3",
            "name": "Vaishali Nagar Clinic Zone",
            "lat": 26.9146,
            "lng": 75.7408,
            "bloodType": "AB-",
            "features": [2, 2, 500, 6, 8, 4, 1]  # High risk traffic + weekend
        }
    ]

    predictions = []

    for region in regions:
        if MODELS_LOADED:
            input_data = pd.DataFrame([region["features"]], columns=FEATURE_NAMES)
            is_shortage = int(classifier.predict(input_data)[0])
            units_needed = int(regressor.predict(input_data)[0])
        else:
            is_shortage = 1 if region["features"][4] > 7 else 0
            units_needed = region["features"][4] * 5

        severity = "Normal"
        if is_shortage == 1 and units_needed > 30:
            severity = "High"
        elif is_shortage == 1:
            severity = "Medium"
        elif units_needed > 10:
            severity = "Low"

        # Human-readable XAI reason
        reason_parts = []
        if region["features"][4] >= 8: reason_parts.append("Severe Accident Risk Forecast")
        if region["features"][5] >= 4: reason_parts.append("Adverse Weather Conditions")
        if region["features"][6] == 1: reason_parts.append("Historically High-Demand Weekend")
        reason_str = " + ".join(reason_parts) if reason_parts else "Routine operational fluctuations."

        # Region-level feature activation scores (0–100), weighted by this region's input
        raw = region["features"]
        local_scores = {
            "Accident Zone Risk": round(min(raw[4] / 10 * 100, 100), 1),
            "Weather Severity":   round(min(raw[5] / 5  * 100, 100), 1),
            "Weekend Demand":     round(raw[6] * 100.0, 1),
            "Donation Frequency": round(min(raw[1] / 50 * 100, 100), 1),
            "Recency":            round(max(0, 100 - raw[0] / 48 * 100), 1),
            "Donor Tenure":       round(min(raw[3] / 98 * 100, 100), 1),
            "Blood Volume (cc)":  round(min(raw[2] / 12500 * 100, 100), 1),
        }

        if severity != "Normal":
            predictions.append({
                "id": region["id"],
                "name": region["name"],
                "lat": region["lat"],
                "lng": region["lng"],
                "severity": severity,
                "reason": reason_str,
                "predictedShortage": max(units_needed, 0),
                "bloodType": region["bloodType"],
                "featureImportances": FEATURE_IMPORTANCES,  # Global model-level importances
                "localScores": local_scores,                 # This region's input-level scores
            })

    return predictions
